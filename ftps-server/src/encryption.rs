use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use hkdf::Hkdf;
use sha2::Sha256;

/// Derive a 32-byte SSE-C encryption key for a user using HKDF-SHA256.
///
/// Must produce identical output to the Node.js implementation:
/// ```js
/// const ikm = Buffer.from(masterKey, 'utf-8');
/// const salt = Buffer.from(userSalt, 'base64url');
/// const info = Buffer.from('clipnest-sse-c-v1', 'utf-8');
/// const derived = crypto.hkdfSync('sha256', ikm, salt, info, 32);
/// ```
pub fn derive_user_key(master_key: &str, user_salt: &str) -> [u8; 32] {
    let ikm = master_key.as_bytes();
    let salt = URL_SAFE_NO_PAD
        .decode(user_salt)
        .expect("invalid base64url salt");
    let info = b"clipnest-sse-c-v1";

    let hkdf = Hkdf::<Sha256>::new(Some(&salt), ikm);
    let mut okm = [0u8; 32];
    hkdf.expand(info, &mut okm).expect("HKDF expand failed");
    okm
}

/// Compute SSE-C header values for S3 operations.
///
/// Returns (algorithm, key_base64, key_md5_base64).
pub fn ssec_headers(key: &[u8; 32]) -> (String, String, String) {
    use base64::engine::general_purpose::STANDARD;
    use md5::{Digest, Md5};

    let algorithm = "AES256".to_string();
    let key_b64 = STANDARD.encode(key);
    let mut hasher = Md5::new();
    hasher.update(key);
    let key_md5 = STANDARD.encode(hasher.finalize());
    (algorithm, key_b64, key_md5)
}

#[cfg(test)]
mod tests {
    use super::*;

    ///story: Klucze per-user wyprowadzone HKDF-SHA256 są bitowo zgodne z wersją Node — gwarancja, że plik zaszyfrowany przez FTPS da się odszyfrować przez API.
    #[test]
    fn test_derive_user_key_matches_nodejs() {
        // Reference value generated by Node.js:
        // node -e "const c = require('crypto');
        //   const key = Buffer.from(c.hkdfSync('sha256', 'testkey',
        //     Buffer.from('dGVzdHNhbHQ', 'base64url'),
        //     Buffer.from('clipnest-sse-c-v1'), 32));
        //   console.log(key.toString('hex'))"
        // Output: d1ffb4baebfbfcbd72477c9779c30efce44c565ecfd0b38c0a0dde7bcc9f6b6b
        let key = derive_user_key("testkey", "dGVzdHNhbHQ");
        let hex = key.iter().map(|b| format!("{:02x}", b)).collect::<String>();
        assert_eq!(
            hex, "d1ffb4baebfbfcbd72477c9779c30efce44c565ecfd0b38c0a0dde7bcc9f6b6b",
            "HKDF output must match Node.js reference"
        );
    }

    ///story: Każdy użytkownik ma unikalny klucz SSE-C dzięki różnym saltom — nagrania jednego klienta pozostają niedostępne dla drugiego, nawet przy wspólnym master key.
    #[test]
    fn test_different_salts_different_keys() {
        let key1 = derive_user_key("masterkey", "c2FsdDE");
        let key2 = derive_user_key("masterkey", "c2FsdDI");
        assert_ne!(key1, key2, "Different salts must produce different keys");
    }

    ///story: Nagłówki SSE-C (algorytm, klucz base64, MD5 klucza) mają dokładnie ten format, którego oczekuje S3 — upload nagrań kamer nie zostanie odrzucony przez bucket.
    #[test]
    fn test_ssec_headers_format() {
        let key = derive_user_key("testkey", "dGVzdHNhbHQ");
        let (algo, key_b64, md5_b64) = ssec_headers(&key);
        assert_eq!(algo, "AES256");
        assert!(!key_b64.is_empty());
        assert!(!md5_b64.is_empty());
        // Key base64 should decode to 32 bytes
        use base64::engine::general_purpose::STANDARD;
        let decoded = STANDARD.decode(&key_b64).unwrap();
        assert_eq!(decoded.len(), 32);
    }
}
